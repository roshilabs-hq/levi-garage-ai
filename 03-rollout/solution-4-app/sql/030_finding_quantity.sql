-- 030: כמות בממצא (סבב 2.10, ממצא 10: "יש רק גלגל אחד ואין אפשרות לתמחר כמה גלגלים").
--
-- המחירים ושעות העבודה בממצא נשארים **הסכום הכולל** (כמות × מחיר ליחידה), והכותרת
-- ללקוח היא "2 × החלפת צמיג". כך דף האישור, המייל, חוקי ס' 132 וההנחה עובדים בלי
-- שינוי. הכמות נשמרת כדי שהטופס של דניאל יידע לחזור למחיר ליחידה.
alter table public.findings
  add column if not exists quantity smallint not null default 1
  check (quantity between 1 and 20);
