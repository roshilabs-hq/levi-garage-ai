// עברית בתוך שורה בערבית או ברוסית: כל קטע עברי (כולל הגרשיים שסביבו) נעטף ב-bdi,
// כדי שהפסיק והגרש שבתוכו לא יקפצו לצד השני של השורה.
const HEB_RUN = /('?[֐-׿][֐-׿ ,]*[֐-׿]'?)/g

function Mixed({ text, lang }: { text: string; lang: Lang }) {
  if (lang === "he") return <>{text}</>
  return (
    <>
      {text.split(HEB_RUN).map((part, i) =>
        i % 2 === 1 ? (
          <bdi key={i} lang="he">
            {part}
          </bdi>
        ) : (
          part
        ),
      )}
    </>
  )
}

export default async function StationCardPage({ searchParams }: { searchParams: Promise<{ lang?: string; print?: string }> }) {
  await requireStaff()
  const { lang: raw, print } = await searchParams
  const lang: Lang = raw === "ar" || raw === "ru" ? raw : "he"
  const c = CARD[lang]

  return (
    <main className="scard-wrap">
      <AutoPrint when={print === "1"} />
      <nav className="scard-nav no-print" dir="rtl">
        <Link href="/staff/stations">חזרה לעמדות</Link>
        {(["he", "ar", "ru"] as const).map((l) => (
          <Link key={l} href={`/staff/station-card?lang=${l}`} aria-current={l === lang ? "page" : undefined}>
            {l === "he" ? "עברית" : l === "ar" ? "العربية" : "Русский"}
          </Link>
        ))}
        <Link className="btn" href={`/staff/station-card?lang=${lang}&print=1`}>להדפסה</Link>
      </nav>

      <article className="scard" dir={c.dir} lang={lang}>
        <header>
          <PlateLogo lang={lang} height={54} mono />
          <div>
            <h1>{c.title}</h1>
            <p>{c.sub}</p>
          </div>
        </header>
        <ol>
          {c.steps.map((s, i) => (
            <li key={i}>
              {s.btn && (
                <b className="scard-btn" dir="rtl" lang="he">
                  {s.btn}
                </b>
              )}{" "}
              <span>
                <Mixed text={s.text} lang={lang} />
              </span>
            </li>
          ))}
        </ol>
        <p className="scard-rule">
          <Mixed text={c.rule} lang={lang} />
        </p>
        <p className="scard-help">
          <Mixed text={c.help} lang={lang} />
        </p>
      </article>
    </main>
  )
}
