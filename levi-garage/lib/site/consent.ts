// הלב של כל הודעה, בלי האימוג'י והפתיחה, כדי שגם עריכה קלה של הלקוח תיתפס.
const PHRASES = [
  "אשמח לקבל תזכורת",
  "אשמח לקבל בוואטסאפ",
  "אשמח לקבל עדכונים",
  "أرجو تذكيري",
  "Пришлите, пожалуйста, напоминание",
]

const norm = (s: string) => s.replace(/\s+/g, " ").trim().toLowerCase()

export function asksForUpdates(text: string): boolean {
  const t = norm(text)
  return PHRASES.some((p) => t.includes(norm(p)))
}

// 4.10: "הסר" מבטל את ההסכמה, כמו שמדיניות הפרטיות מבטיחה (041). רק הודעה
// שכולה בקשת הסרה, כדי ש"הסרתי את הגלגל" לא יבטל כלום.
const REMOVE = ["הסר", "הסר אותי", "הסירו אותי", "הסרה", "תסירו אותי", "stop", "إزالة", "ازالة", "стоп", "отписаться"]

export function wantsRemoval(text: string): boolean {
  const t = norm(text).replace(/[.!?,"'״׳🙂]/g, "").trim()
  return REMOVE.includes(t)
}

